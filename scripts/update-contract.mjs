function publicationDisposition(beforeRule, afterRule, boundaryAction) {
  return {
    beforeDurablePublication: {
      ...beforeRule,
      nextAction: `authenticate-authority-reread-peers-and-repeat-only-${boundaryAction}-publication`,
    },
    afterDurablePublication: {
      ...afterRule,
      nextAction: afterRule === FAULT_DISPOSITION_RULES.forward
        ? `authenticate-authority-reopen-verify-and-idempotently-complete-${boundaryAction}`
        : afterRule.nextAction,
    },
  };
}

