function mapFaults(faultClasses, rule, faultRules = {}) {
  return Object.fromEntries(faultClasses.map((faultClass) => [faultClass, { ...(faultRules[faultClass] ?? rule) }]));
}

function faultBoundary({
  id, group, lifecycleState, durableEvidence, detector, authorizedNextActor,
  requiredAuthority, idempotence, rule, nextAction = rule.nextAction,
  workAdmission, serviceAdmission, userVisibleResult,
  releaseCondition = rule.releaseCondition, faultClasses, mutationAllowed = false,
  faultRules = {}, publicationFailureDisposition,
}) {
  return {
    id, group, lifecycleState, durableEvidence, detector, authorizedNextActor,
    requiredAuthority, idempotence,
    disposition: "fault-class-mapped-deterministically",
    nextAction, workAdmission, serviceAdmission, userVisibleResult,
    releaseCondition, faultClasses,
    faultDispositionByClass: mapFaults(faultClasses, rule, faultRules),
    mutationAllowed,
    positiveGuardianHandshakeRequired: mutationAllowed || id === "guardian-authority-record" || [
      "owner-escape-result", "legacy-post-build-continuation-defense", "legacy-owner-exit",
    ].includes(id),
    immutableLegacyPostBuildPath: "must-not-continue",
    ...(publicationFailureDisposition === undefined ? {} : { publicationFailureDisposition }),
  };
}

